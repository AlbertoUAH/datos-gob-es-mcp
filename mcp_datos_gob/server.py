@mcp.tool()
async def search(
    query: str | None = None,
    title: str | None = None,
    publisher: str | None = None,
    theme: str | None = None,
    themes: list[str] | None = None,
    format: str | None = None,
    keyword: str | None = None,
    date_start: str | None = None,
    date_end: str | None = None,
    exact_match: bool = False,
    page: int = 0,
    sort: str | None = None,
    lang: str | None = "es",
    fetch_all: bool = False,
    max_results: int = MAX_SEARCH_RESULTS,
    include_preview: bool = False,
    preview_rows: int = DEFAULT_PREVIEW_ROWS,
    semantic_min_score: float = SEMANTIC_MIN_SCORE,
    license: str | None = None,
    frequency: str | None = None,
) -> str:
    """Search datasets from the Spanish open data catalog (datos.gob.es).

    Two search modes:
    1. Query-based: Natural language query with synonym expansion → semantic re-ranking.
    2. Filter-based: Direct API filtering by title, publisher, theme, etc.

    Results include total_count for the full matching collection.
    Non-semantic results are cached for 10 minutes (configurable via SEARCH_CACHE_TTL).

    Args:
        query: Natural language query (e.g., "accidentes de tráfico en Madrid").
        title: Search text in dataset titles.
        publisher: Publisher ID (e.g., 'EA0010587' for INE).
        theme: Theme ID (e.g., 'economia', 'salud', 'medio-ambiente').
        themes: List of theme IDs for multi-theme search (OR logic).
        format: Format ID (e.g., 'csv', 'json', 'xml').
        keyword: Keyword/tag to filter by.
        date_start: Start date 'YYYY-MM-DDTHH:mmZ'.
        date_end: End date 'YYYY-MM-DDTHH:mmZ'.
        exact_match: If True with title, match whole words only.
        page: Page number (starting from 0).
        sort: Sort field. Use '-' prefix for descending (e.g., '-modified').
        lang: Preferred language ('es', 'en', 'ca', 'eu', 'gl'). Default 'es'.
        fetch_all: If True, fetches all pages up to max_results.
        max_results: Maximum results (default 100, max 100).
        include_preview: Include data preview for CSV/JSON datasets.
        preview_rows: Number of preview rows (default 10, max 50).
        semantic_min_score: Min similarity score 0-1 (default 0.5).
        license: Filter by license type (e.g., 'CC_BY', 'CC0').
        frequency: Filter by update frequency ('P1D', 'P1W', 'P1M', 'P1Y').

    Returns:
        JSON with matching datasets, metadata, and total_count.
    """
    usage_metrics.record_tool_call("search")
    usage_metrics.record_search(
        {
            "query": query,
            "title": title,
            "publisher": publisher,
            "theme": theme,
            "themes": themes,
            "format": format,
            "keyword": keyword,
        }
    )

    is_semantic = bool(query)

    # Cache key for non-semantic (filter-based) searches
    cache_key: str | None = None
    if not is_semantic:
        cache_params = {
            "title": title,
            "publisher": publisher,
            "theme": theme,
            "themes": themes,
            "format": format,
            "keyword": keyword,
            "date_start": date_start,
            "date_end": date_end,
            "exact_match": exact_match,
            "page": page,
            "sort": sort,
            "lang": lang,
            "fetch_all": fetch_all,
            "max_results": max_results,
            "license": license,
            "frequency": frequency,
        }
        cache_key = _get_cache_key(cache_params)
        cached = _get_cached(cache_key)
        if cached is not None:
            import logging

            logging.getLogger("datos_gob_es").debug("cache_hit", key=cache_key)
            return cached

    # Apply synonym expansion to query
    effective_query = query
    if query:
        variants = _expand_query_with_synonyms(query)
        # Use the expanded query (join variants as multi-keyword query)
        if len(variants) > 1:
            # Pass original query — synonym expansion enriches it via keyword injection
            # We use the first synonym variant as the effective query if the original
            # is a single canonical word, otherwise keep original
            effective_query = variants[0]

    result = await _search_datasets_impl(
        query=effective_query,
        title=title,
        publisher=publisher,
        theme=theme,
        themes=themes,
        format=format,
        keyword=keyword,
        date_start=date_start,
        date_end=date_end,
        exact_match=exact_match,
        page=page,
        sort=sort,
        lang=lang,
        fetch_all=fetch_all,
        max_results=max_results,
        include_preview=include_preview,
        preview_rows=preview_rows,
        semantic_min_score=semantic_min_score,
        license=license,
        frequency=frequency,
    )

    # Inject total_count from a lightweight API count query (best-effort)
    try:
        result_obj = json.loads(result)
        if "total_count" not in result_obj:
            # Fetch the count from the same query with page_size=1
            count_data = await _fetch_total_count(
                title=title,
                publisher=publisher,
                theme=theme,
                format=format,
                keyword=keyword,
                date_start=date_start,
                date_end=date_end,
            )
            if count_data is not None:
                result_obj["total_count"] = count_data
                result = json.dumps(result_obj, ensure_ascii=False, indent=2)
    except Exception:
        pass  # total_count is best-effort; don't break the main result

    if cache_key is not None:
        _set_cache(cache_key, result)

    return result


async def _fetch_total_count(
    title: str | None = None,
    publisher: str | None = None,
    theme: str | None = None,
    format: str | None = None,
    keyword: str | None = None,
    date_start: str | None = None,
    date_end: str | None = None,
) -> int | None:
    """Fetch total item count from API for a given filter combination."""
    try:
        pagination = PaginationParams(page=0, page_size=1)
        if title:
            data = await client.search_datasets_by_title(normalize_text(title), pagination)
        elif publisher:
            data = await client.get_datasets_by_publisher(publisher, pagination)
        elif theme:
            data = await client.get_datasets_by_theme(theme, pagination)
        elif format:
            data = await client.get_datasets_by_format(format, pagination)
        elif keyword:
            data = await client.get_datasets_by_keyword(normalize_text(keyword), pagination)
        elif date_start and date_end:
            data = await client.get_datasets_by_date_range(date_start, date_end, pagination)
        else:
            data = await client.search_datasets(pagination)

        result = data.get("result", {})
        return result.get("totalItems") or result.get("total")
    except Exception:
        return None


@mcp.tool()
async def get(
    dataset_id: str,
    include_data: bool = False,
    format: str | None = None,
    max_rows: int | None = None,
    max_mb: int = MAX_DOWNLOAD_MB,
    lang: str | None = "es",
) -> str:
    """Get dataset metadata and optionally download its data.

    Args:
        dataset_id: The dataset identifier (slug from the URL or URI).
        include_data: If True, downloads and includes actual data (default: False).
        format: Preferred format when include_data=True ('csv', 'json').
        max_rows: Maximum rows to return when include_data=True.
        max_mb: Maximum download size in MB (default 10, max 50).
        lang: Preferred language ('es', 'en', 'ca', 'eu', 'gl'). Default 'es'.

    Returns:
        JSON with dataset metadata. If include_data=True, also includes columns and rows.
    """
    usage_metrics.record_tool_call("get")
    usage_metrics.record_dataset_access(dataset_id)

    try:
        data = await client.get_dataset(dataset_id)

        if not include_data:
            return _format_response(data, "dataset", lang)

        max_mb = min(max_mb, MAX_DOWNLOAD_MB)
        distributions = data.get("result", {}).get("primaryTopic", {}).get("distribution", [])

        if isinstance(distributions, dict):
            distributions = [distributions]

        if not distributions:
            return json.dumps(
                {"error": "No distributions found for this dataset"}, ensure_ascii=False
            )

        # Find best distribution matching preferred format
        best_dist = None
        for dist in distributions:
            dist_format = dist.get("format", "")
            if isinstance(dist_format, dict):
                dist_format = dist_format.get("_value", "")

            normalized = _normalize_format(dist_format, dist.get("mediaType"))
            if format and normalized == format.lower():
                best_dist = dist
                break
            if not best_dist and normalized in ("csv", "json", "tsv"):
                best_dist = dist

        if not best_dist and distributions:
            best_dist = distributions[0]

        if not best_dist:
            return json.dumps(
                {"error": "No suitable distribution found"}, ensure_ascii=False
            )

        access_url = best_dist.get("accessURL") or best_dist.get("downloadURL")
        if not access_url:
            return json.dumps({"error": "No access URL found"}, ensure_ascii=False)

        from server import _fetch_data_preview

        preview = await _fetch_data_preview(
            access_url,
            best_dist.get("format"),
            best_dist.get("mediaType"),
            max_rows or 100,
        )

        base = _format_response(data, "dataset", lang)
        base_obj = json.loads(base)
        if preview:
            base_obj["data_preview"] = preview
        return json.dumps(base_obj, ensure_ascii=False, indent=2)

    except Exception as e:
        return _handle_error(e)


