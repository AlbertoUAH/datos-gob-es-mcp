# ---------------------------------------------------------------------------
# Synonym expansion for datos.gob.es queries (Fase 2.2)
# ---------------------------------------------------------------------------
DATOS_GOB_SYNONYMS: dict[str, list[str]] = {
    "empleo": ["desempleo", "paro", "trabajo", "laboral", "ocupacion"],
    "economia": ["hacienda", "presupuesto", "finanzas", "PIB"],
    "salud": ["sanidad", "hospitales", "medico", "farmacia"],
    "educacion": ["escuelas", "universidades", "ensenanza"],
    "transporte": ["ferroviario", "carreteras", "aeropuertos"],
    "medioambiente": ["contaminacion", "residuos", "emisiones", "clima"],
    "vivienda": ["inmobiliario", "hipotecas", "alquiler"],
    "turismo": ["turistas", "hosteleria", "hotelera"],
    "poblacion": ["censo", "demografico", "padron", "habitantes"],
    "presupuesto": ["gasto", "ingresos", "deuda", "deficit"],
}

# Reverse index: synonym → canonical
_SYNONYM_REVERSE: dict[str, str] = {}
for _canonical, _syns in DATOS_GOB_SYNONYMS.items():
    for _s in _syns:
        _SYNONYM_REVERSE[_s.lower()] = _canonical


def _expand_query_with_synonyms(query: str) -> list[str]:
    """Return a list of query variants expanding known synonyms.

    The original query is always included. For each word in the query that
    matches a canonical term or a known synonym, additional variants are
    generated by substituting the word with its synonyms.
    """
    normalized = normalize_text(query.lower())
    words = normalized.split()
    extra_variants: list[str] = []

    for word in words:
        canonical = _SYNONYM_REVERSE.get(word) or (word if word in DATOS_GOB_SYNONYMS else None)
        if canonical:
            syns = DATOS_GOB_SYNONYMS.get(canonical, [])
            for syn in syns:
                if syn.lower() != word:
                    variant = query.replace(word, syn)
                    if variant not in extra_variants and variant != query:
                        extra_variants.append(variant)

    return [query] + extra_variants


# ---------------------------------------------------------------------------
# Search result cache with TTL (Fase 2.3)
# ---------------------------------------------------------------------------
_SEARCH_CACHE: dict[str, tuple[str, float]] = {}
SEARCH_CACHE_TTL: int = int(os.environ.get("SEARCH_CACHE_TTL", "600"))  # 10 min default


def _get_cache_key(params: dict) -> str:
    return hashlib.md5(json.dumps(params, sort_keys=True).encode()).hexdigest()


def _get_cached(key: str) -> str | None:
    if key in _SEARCH_CACHE:
        result, ts = _SEARCH_CACHE[key]
        if time.time() - ts < SEARCH_CACHE_TTL:
            return result
        del _SEARCH_CACHE[key]
    return None


def _set_cache(key: str, result: str) -> None:
    _SEARCH_CACHE[key] = (result, time.time())


